#!/usr/bin/env node
// Regenerates examples.js: runs every demo query through
// `EXPLAIN QUERY PLAN FORMAT=JSON` on a fresh demo database and stores the
// resulting plans. Usage:
//
//   node scripts/gen-examples.mjs [path-to-tursodb]
//
// Needs a tursodb built with FORMAT=JSON support (turso PR #8316).
import { execFileSync } from "node:child_process";
import { mkdtempSync, rmSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const tursodb = process.argv[2] || "tursodb";
const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

const EXAMPLES = [
  ["Kitchen sink: CTE + EXISTS + subqueries + group/sort", `WITH big_spenders AS (
  SELECT user_id, sum(amount) AS total
  FROM orders GROUP BY user_id
)
SELECT c.name, count(*) AS n
FROM users u
JOIN cities c ON c.id = u.city_id
LEFT JOIN orders o ON o.user_id = u.id
WHERE u.age IN (SELECT age FROM users WHERE city_id = 3)
  AND EXISTS (SELECT 1 FROM big_spenders s WHERE s.user_id = u.id)
  AND u.id > (SELECT avg(user_id) FROM big_spenders)
GROUP BY c.name
ORDER BY n DESC;`],
  ["Index search + left join + sort", `SELECT u.name, o.amount
FROM users u
LEFT JOIN orders o ON o.user_id = u.id
WHERE u.age > 21
ORDER BY o.amount DESC;`],
  ["Shared CTE used twice", `WITH spenders AS (
  SELECT user_id, sum(amount) AS total
  FROM orders GROUP BY user_id
)
SELECT u.name, s1.total
FROM users u
JOIN spenders s1 ON s1.user_id = u.id
JOIN spenders s2 ON s2.user_id = u.city_id;`],
  ["Coroutine subquery + group by", `SELECT city_id, avg(age)
FROM (SELECT * FROM users WHERE age > 18)
GROUP BY city_id
ORDER BY avg(age);`],
  ["UNION with sort", `SELECT name FROM users WHERE age > 30
UNION
SELECT name FROM cities
ORDER BY name;`],
  ["Correlated + IN subqueries", `SELECT u.name,
  (SELECT count(*) FROM orders o WHERE o.user_id = u.id)
FROM users u
WHERE u.age IN (SELECT age FROM users WHERE city_id = 3);`],
  ["EXISTS (semi join)", `SELECT * FROM users u
WHERE EXISTS (SELECT 1 FROM orders o WHERE o.user_id = u.id);`],
  ["Hash join (no usable index)", `SELECT u.name, s.device
FROM users u
JOIN sessions s ON s.session_key = 'sk_' || u.id
JOIN events e ON e.session_key = s.session_key;`],
  ["Multi-index OR", `SELECT * FROM users WHERE id = 5 OR age = 30;`],
  ["Recursive CTE", `WITH RECURSIVE cnt(x) AS (
  SELECT 1
  UNION ALL
  SELECT x + 1 FROM cnt WHERE x < 10
)
SELECT x FROM cnt;`],
  ["Window function", `SELECT name,
  row_number() OVER (PARTITION BY city_id ORDER BY age)
FROM users;`],
];

const workDir = mkdtempSync(join(tmpdir(), "planviz-examples-"));
const dbPath = join(workDir, "demo.db");
try {
  const schema = readFileSync(join(repoRoot, "scripts", "demo-schema.sql"), "utf8");
  execFileSync(tursodb, [dbPath, "-q"], { input: schema, stdio: ["pipe", "pipe", "inherit"] });

  const examples = [];
  for (const [name, sql] of EXAMPLES) {
    const out = execFileSync(tursodb, [dbPath, "-q"], {
      input: `EXPLAIN QUERY PLAN FORMAT=JSON ${sql}\n`,
      stdio: ["pipe", "pipe", "inherit"],
    }).toString().trim();
    let plan;
    try {
      plan = JSON.parse(out);
    } catch (e) {
      throw new Error(`"${name}" did not produce JSON. Output:\n${out}`);
    }
    if (!Array.isArray(plan.nodes) || plan.nodes.length === 0) {
      throw new Error(`"${name}" produced a plan without nodes:\n${out}`);
    }
    examples.push({ name, plan });
    console.log(`ok: ${name} (${plan.nodes.length} nodes)`);
  }

  const banner =
    "// Generated by scripts/gen-examples.mjs — do not edit by hand.\n" +
    "// Pre-computed EXPLAIN QUERY PLAN FORMAT=JSON output for the demo\n" +
    "// schema in scripts/demo-schema.sql, so the tool can demo itself\n" +
    "// without a database.\n";
  writeFileSync(
    join(repoRoot, "examples.js"),
    `${banner}window.PLAN_EXAMPLES = ${JSON.stringify(examples, null, 1)};\n`,
  );
  console.log(`\nwrote examples.js (${examples.length} plans)`);
} finally {
  rmSync(workDir, { recursive: true, force: true });
}
